"""Build the Shelf2Site logo files from one definition.

Writes the mark and wordmark SVGs under static/img, the PWA icons under
static/icons, and app/templates/_brand.html (inline macros whose wordmark
follows the theme text color). The wordmark is Space Grotesk Bold, turned
into outlines so the SVGs look the same without the font installed.

Development only; needs fonttools and cairosvg:
    pip install fonttools cairosvg
    python scripts/brand/build_logo.py
"""
from pathlib import Path

import cairosvg
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
FONT = ROOT / "static/fonts/space-grotesk-700.ttf"
TEAL_LIGHT, TEAL_DARK, PIN = "#1690BC", "#0B5E7E", "#F2C9C4"
INK_LIGHT, INK_DARK = "#0F2530", "#EAF2F5"

# The mark on a 64 x 64 tile: two boxes on a shelf, a dotted route lifting
# off the shelf, and the site pin it ends at.
MARK_BODY = (
    '<rect x="11" y="45" width="30" height="3.2" rx="1.6" fill="#fff"/>'
    '<rect x="12.5" y="31" width="13" height="13" rx="2.4" fill="#fff"/>'
    '<rect x="17.7" y="31" width="2.6" height="5" fill="{dark}" opacity=".55"/>'
    '<rect x="27.5" y="35.5" width="9.5" height="8.5" rx="2" fill="#fff" opacity=".82"/>'
    '<path d="M24 26.5 C 28 15, 36 12.5, 42.5 17.5" fill="none" stroke="#fff" '
    'stroke-width="2.6" stroke-linecap="round" stroke-dasharray="0.1 5.2"/>'
    '<path d="M49 43 C 49 43 40.5 33.8 40.5 26.8 a8.5 8.5 0 0 1 17 0 C 57.5 33.8 49 43 49 43 Z" fill="{pin}"/>'
    '<circle cx="49" cy="26.6" r="3.3" fill="{dark}"/>'
)


def tile(uid, pad=0.0):
    """The mark as SVG body inside a 64 box; pad shrinks it for maskable icons."""
    scale = 1 - 2 * pad
    grad = (f'<defs><linearGradient id="{uid}" x1="0" y1="0" x2="1" y2="1">'
            f'<stop offset="0" stop-color="{TEAL_LIGHT}"/><stop offset="1" stop-color="{TEAL_DARK}"/>'
            f'</linearGradient></defs>')
    if pad:
        bg = f'<rect width="64" height="64" fill="url(#{uid})"/>'
    else:
        bg = f'<rect width="64" height="64" rx="14" fill="url(#{uid})"/>'
    body = MARK_BODY.format(dark=TEAL_DARK, pin=PIN)
    inner = f'<g transform="translate({32 - 32 * scale} {32 - 32 * scale}) scale({scale})">{body}</g>'
    return grad + bg + inner


def wordmark_paths():
    """('Shelf', '2', 'Site') outlines in font units, plus total advance and cap box."""
    font = TTFont(FONT)
    cmap, gs, hmtx = font.getBestCmap(), font.getGlyphSet(), font["hmtx"]
    upm = font["head"].unitsPerEm
    parts, x = [], 0
    for chunk in ("Shelf", "2", "Site"):
        pen = SVGPathPen(gs)
        for ch in chunk:
            name = cmap[ord(ch)]
            gs[name].draw(TransformPen(pen, (1, 0, 0, -1, x, 0)))
            x += hmtx[name][0]
        parts.append(pen.getCommands())
    cap = font["OS/2"].sCapHeight
    return parts, x, cap, upm


PARTS, ADVANCE, CAP, UPM = wordmark_paths()


def horizontal(ink, uid, accent=TEAL_LIGHT):
    """Mark plus wordmark, 64 units tall; returns (svg body, width)."""
    k = 30 / CAP                      # cap height 30 of the 64-unit mark
    gap = 14
    width = 64 + gap + ADVANCE * k + 4
    base = 32 + 15                    # baseline so the caps sit centred
    shelf, two, site = PARTS
    words = (f'<g transform="translate({64 + gap} {base}) scale({k:.5f})">'
             f'<path d="{shelf}" fill="{ink}"/><path d="{two}" fill="{accent}"/>'
             f'<path d="{site}" fill="{ink}"/></g>')
    return tile(uid) + words, width


def svg(body, w, h):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w:.1f} {h}" '
            f'role="img" aria-label="Shelf2Site">{body}</svg>\n')


def main():
    img = ROOT / "static/img"
    icons = ROOT / "static/icons"
    (img / "logo-mark.svg").write_text(svg(tile("s2s-g"), 64, 64))
    for name, ink in (("logo-horizontal-light.svg", INK_LIGHT), ("logo-horizontal-dark.svg", INK_DARK)):
        body, w = horizontal(ink, "s2s-g")
        (img / name).write_text(svg(body, w, 64))
    for size in (72, 96, 128, 144, 152, 192, 384, 512):
        cairosvg.svg2png(bytestring=svg(tile("g"), 64, 64).encode(), write_to=str(icons / f"icon-{size}.png"),
                         output_width=size, output_height=size)
    for size in (192, 512):
        cairosvg.svg2png(bytestring=svg(tile("g", pad=0.12), 64, 64).encode(),
                         write_to=str(icons / f"icon-{size}-maskable.png"), output_width=size, output_height=size)
    # Inline macros: the wordmark takes the text color, so one logo serves
    # both themes. Each call site passes its own gradient id.
    body, w = horizontal("currentColor", "{{ uid }}", accent="var(--brand-accent, #1690BC)")
    mark = tile("{{ uid }}")
    macros = (
        "{# Generated by scripts/brand/build_logo.py; edit that, not this. #}\n"
        "{% macro brand_logo(height=36, uid='s2s-logo') -%}\n"
        f'<svg class="brand-logo" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w:.1f} 64" '
        f'height="{{{{ height }}}}" role="img" aria-label="Shelf2Site">{body}</svg>\n'
        "{%- endmacro %}\n"
        "{% macro brand_mark(size=34, uid='s2s-mark') -%}\n"
        '<svg class="brand-mark" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" '
        f'width="{{{{ size }}}}" height="{{{{ size }}}}" role="img" aria-label="Shelf2Site">{mark}</svg>\n'
        "{%- endmacro %}\n"
    )
    (ROOT / "app/templates/_brand.html").write_text(macros)
    print("wrote logo files; wordmark advance", ADVANCE, "upm", UPM)


if __name__ == "__main__":
    main()
