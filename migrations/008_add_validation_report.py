"""Migration: Add validation report fields to device_provisioning.

Stores the file path, overall result, and date of edge box validation reports
generated by validate.py. Reports are uploaded during the Certified
stage as part of the device certification process.

New fields:
- validation_report_path: Path to stored JSON report file
- validation_result: Overall result (PASS, FAIL, WARN)
- validation_date: When the validation was run

Run this migration on the server with:
    cd /opt/asset_tracker
    source venv/bin/activate
    python migrations/008_add_validation_report.py
"""

import sys
from pathlib import Path

# Add parent directory to path for imports
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from sqlalchemy import text
from app.database import engine


ADD_COLUMNS = """
ALTER TABLE device_provisioning
ADD COLUMN IF NOT EXISTS validation_report_path VARCHAR(512),
ADD COLUMN IF NOT EXISTS validation_result VARCHAR(16),
ADD COLUMN IF NOT EXISTS validation_date TIMESTAMP;
"""


def run_migration():
    """Add validation report fields to device_provisioning table."""

    with engine.begin() as conn:
        conn.execute(text(ADD_COLUMNS))
        print("  Added columns: validation_report_path, validation_result, validation_date")

    print("\nMigration 008 complete: Validation report fields added to device_provisioning.")


if __name__ == "__main__":
    print("Running migration 008: Add validation report fields to device_provisioning...")
    run_migration()
